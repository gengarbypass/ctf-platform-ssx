"use strict";

const board = document.getElementById("ctf-scoreboard");
const query = selector => board.querySelector(selector);
const content = query("[data-board-content]");
const playback = query("[data-board-playback]");
const fullscreen = query("[data-board-fullscreen]");
const feedback = query("[data-board-feedback]");
const status = query("[data-board-status]");
const clock = query("[data-board-clock]");
const segments = query("[data-board-segments]");
const formatPoints = new Intl.NumberFormat("zh-CN");
const reduced = matchMedia("(prefers-reduced-motion: reduce)");
const pauseDelay = Number(board.dataset.boardPoll) * 1000;
let timing = JSON.parse(board.dataset.boardTiming);
let receivedAt = performance.now();
let contentMarkup = null;
let progressSignature = null;
let paused = false;
let timer;
let connection;
let animationFrame;

function updateClock() {
  if (paused) return;
  const seconds = Math.max(0, timing.clock_end - timing.now - Math.floor((performance.now() - receivedAt) / 1000));
  clock.textContent = displayDuration(seconds, board.dataset.boardHours === "1");
  clock.dateTime = `PT${seconds}S`;
}

function renderTiming() {
  status.textContent = timing.status;
  status.classList.remove("is-paused");
  query("[data-board-title]").textContent = timing.title;
  query("[data-board-schedule]").textContent = timing.schedule;
  query("[data-board-clock-label]").textContent = timing.clock_label;
  if (segments) {
    query("[data-board-round-panel]").hidden = timing.id === null;
    query("[data-board-round]").textContent = timing.round_label;
    query("[data-board-start]").textContent = `${timing.start_label} 开赛`;
    query("[data-board-end]").textContent = `${timing.end_label} 结束`;
    const signature = timing.segments.join("|");
    if (signature !== progressSignature) {
      progressSignature = signature;
      segments.style.gridTemplateColumns = `repeat(${timing.segments.length || 1}, minmax(0,1fr))`;
      segments.replaceChildren(...timing.segments.map(segment => {
        const bar = document.createElement("i");
        bar.className = segment;
        return bar;
      }));
    }
  }
  updateClock();
}

function updateRankShift(row, before, rank) {
  const delta = before - rank;
  if (!delta) return;
  const label = row.querySelector("[data-sb-shift]");
  label.textContent = `${delta > 0 ? "↑" : "↓"}${Math.abs(delta)}`;
  label.classList.add(delta > 0 ? "gain" : "loss");
  label.setAttribute("aria-label", `名次${delta > 0 ? "上升" : "下降"} ${Math.abs(delta)} 位`);
}

function renderContent(markup, sameContest) {
  if (markup === contentMarkup && sameContest) return;
  contentMarkup = markup;
  cancelAnimationFrame(animationFrame);
  const oldTeams = new Map(Array.from(content.querySelectorAll("[data-sb-team]"), row => [
    row.dataset.sbTeam,
    { rect: row.getBoundingClientRect(), rank: Number(row.dataset.sbRank), points: Number(row.querySelector("[data-sb-value]").dataset.sbValue) },
  ]));
  const oldHealth = new Map(Array.from(content.querySelectorAll("[data-sb-service]"), cell => [cell.dataset.sbService, cell.dataset.sbHealth]));
  const oldEvent = content.querySelector(".is-latest")?.dataset.sbEvent;
  // The same-origin fragment is generated by the auto-escaped board template.
  content.innerHTML = markup;
  if (!sameContest) return;
  const animated = [];
  for (const row of content.querySelectorAll("[data-sb-team]")) {
    const before = oldTeams.get(row.dataset.sbTeam);
    if (!before) continue;
    updateRankShift(row, before.rank, Number(row.dataset.sbRank));
    if (reduced.matches) continue;
    const after = row.getBoundingClientRect();
    const x = before.rect.left - after.left;
    const y = before.rect.top - after.top;
    if (Math.abs(x) + Math.abs(y) > 1) {
      row.animate([{ transform: `translate(${x}px,${y}px)`, opacity: .72 }, { transform: "translate(0,0)", opacity: 1 }],
        { duration: 570, easing: "cubic-bezier(.22,.75,.26,1)" });
    }
    const value = row.querySelector("[data-sb-value]");
    const score = Number(value.dataset.sbValue);
    if (before.points !== score) {
      row.classList.add("is-changed");
      animated.push({ value, from: before.points, to: score });
    }
  }
  if (!reduced.matches) {
    for (const cell of content.querySelectorAll("[data-sb-service]")) {
      if (oldHealth.has(cell.dataset.sbService) && oldHealth.get(cell.dataset.sbService) !== cell.dataset.sbHealth) {
        cell.querySelector(".sb-health-chip").animate([{ transform: "scale(1.35)" }, { transform: "scale(1)" }], { duration: 520 });
      }
    }
  }
  const latest = content.querySelector(".is-latest");
  if (latest && latest.dataset.sbEvent !== oldEvent) {
    query("[data-board-announcement]").textContent = latest.innerText;
    if (!reduced.matches) {
      latest.animate([{ opacity: .45, transform: "translateY(7px)" }, { opacity: 1, transform: "translateY(0)" }], { duration: 410 });
      query(".sb-sweep").animate([
        { opacity: 0, transform: "translateX(0)" }, { opacity: 1, offset: .27 }, { opacity: 0, transform: "translateX(400%)" },
      ], { duration: 830, easing: "ease-out" });
    }
  }
  if (!animated.length) return;
  const started = performance.now();
  function frame(now) {
    const progress = Math.min(1, (now - started) / 570);
    for (const entry of animated) {
      entry.value.textContent = formatPoints.format(Math.round(entry.from + (entry.to - entry.from) * (1 - (1 - progress) ** 3)));
    }
    if (progress < 1) animationFrame = requestAnimationFrame(frame);
  }
  animationFrame = requestAnimationFrame(frame);
}

async function refresh() {
  if (paused || connection) return;
  const controller = new AbortController();
  connection = controller;
  const deadline = setTimeout(() => controller.abort(), 7000);
  try {
    const response = await fetch(board.dataset.boardApi, { cache: "no-store", signal: controller.signal, headers: { Accept: "application/json" } });
    if (!response.ok || !response.headers.get("content-type")?.includes("application/json")) throw new Error("Invalid update response");
    const next = await response.json();
    if (paused || controller.signal.aborted) return;
    const sameContest = timing.id === next.timing.id;
    timing = next.timing;
    receivedAt = performance.now();
    renderContent(next.content, sameContest);
    renderTiming();
    feedback.hidden = true;
  } catch {
    if (!paused) {
      status.textContent = "更新暂不可用";
      status.classList.add("is-paused");
      feedback.textContent = "暂时无法刷新，正在重试。";
      feedback.hidden = false;
    }
  } finally {
    clearTimeout(deadline);
    connection = null;
    if (!paused) timer = setTimeout(refresh, pauseDelay);
  }
}

playback.addEventListener("click", () => {
  paused = !paused;
  playback.textContent = paused ? "继续" : "暂停";
  if (paused) {
    clearTimeout(timer);
    connection?.abort();
    cancelAnimationFrame(animationFrame);
    for (const value of content.querySelectorAll("[data-sb-value]")) value.textContent = formatPoints.format(Number(value.dataset.sbValue));
    status.textContent = "已暂停";
    status.classList.add("is-paused");
  } else {
    refresh();
  }
});

fullscreen.hidden = !document.fullscreenEnabled;
fullscreen.addEventListener("click", async () => {
  try {
    if (document.fullscreenElement === board) await document.exitFullscreen();
    else await board.requestFullscreen();
  } catch {
    feedback.textContent = "当前浏览器无法进入全屏。";
    feedback.hidden = false;
  }
});
document.addEventListener("fullscreenchange", () => {
  fullscreen.textContent = document.fullscreenElement === board ? "退出全屏" : "全屏";
});
renderTiming();
setInterval(updateClock, 500);
timer = setTimeout(refresh, pauseDelay);
